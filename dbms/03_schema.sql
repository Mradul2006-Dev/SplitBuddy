BEGIN;

CREATE SCHEMA splitbuddy;
SET LOCAL search_path TO splitbuddy;

CREATE TABLE users (
    user_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text NOT NULL CHECK (btrim(display_name) <> ''),
    email text NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND position('@' IN email) > 1)
);

CREATE TABLE expense_groups (
    group_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name text NOT NULL CHECK (btrim(group_name) <> ''),
    created_by bigint NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE group_members (
    group_id bigint NOT NULL REFERENCES expense_groups (group_id) ON DELETE RESTRICT,
    user_id bigint NOT NULL REFERENCES users (user_id) ON DELETE RESTRICT,
    joined_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, user_id)
);

CREATE TABLE expenses (
    group_id bigint NOT NULL,
    expense_no bigint GENERATED BY DEFAULT AS IDENTITY,
    paid_by bigint NOT NULL,
    description text NOT NULL CHECK (btrim(description) <> ''),
    amount_paise bigint NOT NULL CHECK (amount_paise > 0),
    split_method text NOT NULL CHECK (split_method IN ('EQUAL', 'CUSTOM')),
    incurred_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (group_id, expense_no),
    FOREIGN KEY (group_id, paid_by) REFERENCES group_members (group_id, user_id) ON DELETE RESTRICT
);

CREATE TABLE expense_splits (
    group_id bigint NOT NULL,
    expense_no bigint NOT NULL,
    user_id bigint NOT NULL,
    share_paise bigint NOT NULL CHECK (share_paise >= 0),
    PRIMARY KEY (group_id, expense_no, user_id),
    FOREIGN KEY (group_id, expense_no) REFERENCES expenses (group_id, expense_no) ON DELETE RESTRICT,
    FOREIGN KEY (group_id, user_id) REFERENCES group_members (group_id, user_id) ON DELETE RESTRICT
);

CREATE TABLE settlements (
    settlement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id bigint NOT NULL,
    from_user_id bigint NOT NULL,
    to_user_id bigint NOT NULL,
    amount_paise bigint NOT NULL CHECK (amount_paise > 0),
    paid_at timestamptz NOT NULL DEFAULT now(),
    CHECK (from_user_id <> to_user_id),
    FOREIGN KEY (group_id, from_user_id) REFERENCES group_members (group_id, user_id) ON DELETE RESTRICT,
    FOREIGN KEY (group_id, to_user_id) REFERENCES group_members (group_id, user_id) ON DELETE RESTRICT
);

COMMIT;
